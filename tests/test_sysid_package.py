"""A saved system-ID package: the measured plant, and its own noise.

Fixtures are synthesized in the layout `save_package_to_netcdf`
writes — (lines, responses, ...) with the sysid settings as group
attributes — with planted values the assertions name. The plate's own
controller-written saves (skipped where stressdata is absent) hold
the layout against the controller's real writer; they are ours,
generated by `generate_plate_sysid.py`, not copied from anywhere.
"""

