@pytest.fixture(autouse=True)
def decline_the_sysid_question(monkeypatch):
    """Importing a quiet-then-loud two-stream file now asks whether it
    is a system ID run; tests not about the question answer No, and
    the ones about it patch their own answer over this."""
    from PySide6.QtWidgets import QMessageBox

    monkeypatch.setattr(
        QMessageBox, 'question',
        staticmethod(lambda *a, **k: QMessageBox.StandardButton.No))

FS = 2048.0
FRAME = 256
LINES = FRAME // 2 + 1


def _write_package(path, noise_level=1e-8, with_indices=True):
    import netCDF4 as nc

    ds = nc.Dataset(str(path), 'w')
    g = ds.createGroup('Random')
    g.sysid_sample_rate = FS
    g.sysid_frame_size = FRAME
    g.createDimension('sysid_fft_lines', LINES)
    g.createDimension('sysid_control_channels', 2)
    g.createDimension('sysid_output_channels', 3)
    if with_indices:
        g.createDimension('control_channels', 2)
        var = g.createVariable('control_channel_indices', 'i4',
                               ('control_channels',))
        var[...] = [3, 6]
    shape3 = ('sysid_fft_lines', 'sysid_control_channels',
              'sysid_output_channels')
    for name, value in (('frf_data_real', 2.0), ('frf_data_imag', 0.5)):
        var = g.createVariable(name, 'f8', shape3)
        var[...] = np.full((LINES, 2, 3), value)
    var = g.createVariable('frf_coherence', 'f8',
                           ('sysid_fft_lines', 'sysid_control_channels'))
    var[...] = np.full((LINES, 2), 0.97)
    for prefix, n, driven in (('response', 'sysid_control_channels', 1e-4),
                              ('reference', 'sysid_output_channels', 4e-5)):
        for kind, level in ((f'{prefix}_cpsd', driven),
                            (f'{prefix}_noise_cpsd', noise_level)):
            for part in ('real', 'imag'):
                var = g.createVariable(f'{kind}_{part}', 'f8',
                                       ('sysid_fft_lines', n, n))
                size = 2 if n == 'sysid_control_channels' else 3
                var[...] = (np.broadcast_to(
                    np.eye(size) * level, (LINES, size, size))
                    if part == 'real' else np.zeros((LINES, size, size)))
    ds.close()
    return str(path)


def test_the_package_imports_its_four_readings(tmp_path):
    path = _write_package(tmp_path / 'sysid.nc4')
    assert rattlesnake.sniff(path)
    out = visualdynamics.import_file(path)
    frf = out['Random_frf']
    assert frf.num_records == 6, '2 responses x 3 drives'
    assert frf.response_dof[:3] == ['4', '4', '4'], \
        'hardware channel numbers, node-only — real, if incomplete'
    assert frf.reference_dof[0] == '9001', \
        'the file never says which channels the drives were'
    assert frf.abscissa[1] == pytest.approx(FS / FRAME), \
        'the line spacing comes from the sysid settings'
    assert frf.ordinate[0, 5] == pytest.approx(2.0 + 0.5j)
    coherence = out['Random_coherence']
    assert coherence.num_records == 2
    assert coherence.ordinate[0, 0] == pytest.approx(0.97)
    # the driven and ambient autospectra arrive as a PSD pair — the
    # ratio is a reading of the two, not a third object
    driven = out['Random_excitation_psds']
    quiet = out['Random_noise_psds']
    assert driven.num_records == quiet.num_records == 5
    assert driven.response_dof == ['4', '7', '9001', '9002', '9003']
    assert driven.ordinate[0, 3] == pytest.approx(1e-4)
    assert driven.ordinate[2, 3] == pytest.approx(4e-5)
    assert quiet.ordinate[0, 3] == pytest.approx(1e-8)


def test_the_pair_divides_to_the_planted_ratio(tmp_path):
    """Driven 1e-4 over ambient 1e-8 is 40 dB, at every line, on the
    response channels; the drives plant 36 dB the same way — read
    through density_ratio, the one rule under every ratio view."""
    from visualdynamics.core.data import density_ratio

    path = _write_package(tmp_path / 'sysid.nc4')
    out = visualdynamics.import_file(path)
    _x, rows, dofs, _dims = density_ratio(out['Random_excitation_psds'],
                                   out['Random_noise_psds'])
    assert dofs == ['4', '7', '9001', '9002', '9003']
    response_db = 10 * np.log10(np.real(rows[0, 1:]))
    assert np.allclose(response_db, 40.0), 'the planted response ratio'
    drive_db = 10 * np.log10(np.real(rows[2, 1:]))
    assert np.allclose(drive_db, 10 * np.log10(4e-5 / 1e-8))


def test_silent_ambient_reads_as_no_ratio_not_infinity(tmp_path):
    """A simulated run measures perfect silence; a zero ambient line
    has nothing to divide by and answers NaN, never infinity."""
    from visualdynamics.core.data import density_ratio

    path = _write_package(tmp_path / 'sysid.nc4', noise_level=0.0)
    out = visualdynamics.import_file(path)
    _x, rows, _dofs, _dims = density_ratio(out['Random_excitation_psds'],
                                    out['Random_noise_psds'])
    assert np.all(np.isnan(np.real(rows)))


def test_the_package_survives_a_project_and_the_native_format(tmp_path):
    path = _write_package(tmp_path / 'sysid.nc4')
    project = visualdynamics.Project('sysid')
    project.import_file(path)
    pair = [name for name in project.names if 'PSD' in name]
    assert len(pair) == 2, 'the driven and ambient densities'
    saved = str(tmp_path / 'sysid.vdyn')
    project.save(saved)
    back = visualdynamics.Project.open(saved)
    for name in pair:
        assert np.allclose(np.real(back[name].ordinate),
                           np.real(project[name].ordinate),
                           equal_nan=True)


