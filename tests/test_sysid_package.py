def test_a_mixed_stream_splits_into_one_figure_per_type():
    """Force and acceleration channels must not share a time axis
    (Brandon, 2026-08-23 — one plot per type): a stream carrying both
    gets one figure per quantity, excitation types first, for each of
    the two streams."""
    from visualdynamics.core.data import TimeHistory
    from visualdynamics.core.report import sysid_template

    t = np.arange(64) / 64.0

    def stream(scale):
        return TimeHistory(
            t, np.ones((3, len(t))) * scale,
            response_dof=['9001X+', '101Z+', '104Z+'],
            ordinate_dim=['force', 'acceleration', 'acceleration'],
            ordinate_unit=['N', 'm/s**2', 'm/s**2'])

    report = sysid_template({'Noise': stream(0.01),
                             'Excitation': stream(1.0)})
    plots = [b for b in report.blocks if b.get('kind') == 'plot'
             and b.get('source') in ('Noise', 'Excitation')]
    assert [(b['source'], b.get('select')) for b in plots] == [
        ('Noise', 'dim:force'), ('Noise', 'dim:acceleration'),
        ('Excitation', 'dim:force'), ('Excitation', 'dim:acceleration')]
    assert 'force' in plots[0]['caption']
    assert 'noise' in plots[0]['caption']


def test_the_densities_overlay_per_quantity_and_pair_by_channel():
    """The noise and excitation densities read together, one figure
    per quantity (Brandon, 2026-08-23) — the driven level solid and
    the ambient one dashed in the same color, so a channel and its
    own floor are one pair. No CMIF: a system ID identifies a plant,
    it does not count modes."""
    from visualdynamics.core.data import Psd
    from visualdynamics.core.report import sysid_template
    from visualdynamics.report import _build_block

    f = np.arange(1.0, 9.0)

    def densities(scale):
        return Psd(f, np.ones((3, len(f))) * scale,
                   response_dof=['9001X+', '101Z+', '104Z+'],
                   ordinate_dim=['force**2/frequency',
                                 'acceleration**2/frequency',
                                 'acceleration**2/frequency'],
                   ordinate_unit=['N', 'm/s**2', 'm/s**2'])

    objects = {'Noise PSDs': densities(1e-4),
               'Excitation PSDs': densities(1.0)}
    report = sysid_template(objects)
    assert not [b for b in report.blocks if b.get('mode') == 'cmif'], \
        'the CMIF is gone from this report'
    # the pair reads on the stage now, one figure per quantity
    # (Brandon, 2026-08-23) — the app's own 3-D overlay
    pairs = [b for b in report.blocks
             if b.get('floor') and b.get('reading') != 'ratio']
    assert [b['quantity'] for b in pairs] == ['force', 'acceleration']
    assert all(b['mode'] == 'stage' for b in pairs)
    assert all(b['source'] == 'Excitation PSDs'
               and b['floor'] == 'Noise PSDs' for b in pairs), \
        'the louder set leads, as it does in the ratio below'
    # the ratio still follows, reading the same pair
    ratio = next(b for b in report.blocks
                 if b.get('reading') == 'ratio')
    assert (ratio['source'], ratio['floor']) == ('Excitation PSDs',
                                                 'Noise PSDs')
    assert report.blocks.index(pairs[-1]) < report.blocks.index(ratio)

    # a stage block answers with the figures it needs; this pair is
    # two channels, so one
    figures = _build_block(pairs[1], objects, visualdynamics.SI, [])
    assert len(figures) == 1
    built = figures[0]
    assert built['kind'] == 'stage'
    assert [r.get('quiet', False) for r in built['runs']] == [
        False, True, False, True], \
        'each station meets its pair: the louder, then the stood-back'
    assert built['labels'][:2] == ['101Z+', '101Z+'], \
        'the acceleration channels only, both sides of each station'


def test_a_silent_channel_is_not_a_legend_entry():
    """The ambient recording of a drive channel is exactly zero — the
    shaker was off — and zero has no place on a log axis. A legend
    entry for a curve that draws nothing is a claim the figure does
    not support, so the curve goes and the caption says why."""
    from visualdynamics.core.data import Psd
    from visualdynamics.report import _build_block

    f = np.arange(1.0, 9.0)
    quiet = Psd(f, np.zeros((1, len(f))), response_dof=['9001X+'],
                ordinate_dim='force**2/frequency', ordinate_unit='N')
    loud = Psd(f, np.ones((1, len(f))), response_dof=['9001X+'],
               ordinate_dim='force**2/frequency', ordinate_unit='N')
    objects = {'Noise': quiet, 'Excitation': loud}
    block = {'kind': 'plot', 'mode': 'pair', 'source': 'Excitation',
             'floor': 'Noise', 'caption': 'Densities overlaid'}
    built = _build_block(block, objects, visualdynamics.SI, [])
    assert [c['label'] for c in built['curves']] == ['Excitation: 9001X+']
    assert 'recorded exactly zero' in built['caption']

    # and with both sides real, nothing is dropped and nothing is said
    objects['Noise'] = Psd(f, np.full((1, len(f)), 1e-6),
                           response_dof=['9001X+'],
                           ordinate_dim='force**2/frequency',
                           ordinate_unit='N')
    built = _build_block(block, objects, visualdynamics.SI, [])
    assert len(built['curves']) == 2
    assert built['caption'] == 'Densities overlaid'
