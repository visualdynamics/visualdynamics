def test_an_import_draws_once_not_per_selection_change(window, pump,
                                                       tmp_path,
                                                       monkeypatch):
    """Importing this file used to render 48 times — every object
    added and every tree reshuffle of the type switch moved the
    selection, and each move rebuilt the view, 31 of them the
    specification's whole 3D stage in front of the user. The import
    suppresses selection renders and draws the final state once."""
    from PySide6.QtWidgets import QMessageBox

    monkeypatch.setattr(QMessageBox, 'question', staticmethod(
        lambda *a, **k: QMessageBox.StandardButton.Yes))
    calls = []
    real = window.render_current
    monkeypatch.setattr(
        window, 'render_current',
        lambda *a, **k: (calls.append(1), real(*a, **k))[1])
    window.import_paths([_write_streamed_sysid(tmp_path / 's.nc4')])
    pump()
    assert len(calls) == 1, \
        f'{len(calls)} renders for one import; the storm is back'
    assert window.project_type == 'System ID'


