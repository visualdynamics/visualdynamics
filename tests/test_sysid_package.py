def test_any_number_of_streams_import_in_order(tmp_path):
    """A run can stop and restart its stream as often as it likes —
    system ID makes two, but nothing limits the count. Twelve
    streams, each louder than the last, import in stream order —
    twelve rather than a few because double digits are where a
    string sort would slide _10 in between _1 and _2."""
    from itertools import pairwise

    import netCDF4 as nc

    path = str(tmp_path / 'many.nc4')
    ds = nc.Dataset(path, 'w')
    ds.file_version = '3.0.0'
    ds.sample_rate = 1024.0
    ds.createDimension('response_channels', 1)
    rng = np.random.default_rng(11)
    for k in range(12):
        suffix = '' if k == 0 else f'_{k}'
        ds.createDimension(f'time_samples{suffix}', 512)
        var = ds.createVariable(f'time_data{suffix}', 'f8',
                                ('response_channels',
                                 f'time_samples{suffix}'))
        var[...] = rng.standard_normal((1, 512)) * 2.0 ** k
    ch = ds.createGroup('channels')
    ch.createDimension('n', 1)
    for name, value in (('node_number', '101'), ('node_direction', 'Z+'),
                        ('unit', 'm/s^2'), ('feedback_device', '')):
        var = ch.createVariable(name, str, ('n',))
        var[0] = value
    ds.close()

    out = visualdynamics.import_file(path)
    keys = ['time_data'] + [f'time_data_{k}' for k in range(2, 13)]
    assert [key for key in out if key.startswith('time_data')] == keys
    levels = [float(out[key].ordinate.std()) for key in keys]
    assert all(b > 1.5 * a for a, b in pairwise(levels)), \
        'stream order held: each one louder than the one before'


def test_two_selected_densities_offer_the_ratio_reading(window, pump):
    """Two plain PSDs selected together read two ways — overlaid, or
    divided in decibels (Brandon, 2026-08-25). The bar offers the
    pair; the ratio draws the louder over the quieter with a linear
    frequency axis, like nearly every plot here."""
    import pyqtgraph as pg

    from visualdynamics.core.data import Psd

    freq = np.linspace(2.0, 1000.0, 500)
    quiet = Psd(abscissa=freq, ordinate=np.full((2, 500), 1e-6),
                response_dof=['101Z+', '104Z+'],
                ordinate_dim=['acceleration**2/frequency'] * 2)
    loud = Psd(abscissa=freq, ordinate=np.full((2, 500), 1e-3),
               response_dof=['101Z+', '104Z+'],
               ordinate_dim=['acceleration**2/frequency'] * 2)
    window.add_object('Noise PSDs', quiet)
    window.add_object('Excitation PSDs', loud)
    pane = window.data_pane
    pane.waterfall_action.setChecked(False)
    window._item_for_object('Noise PSDs').setSelected(True)
    window._item_for_object('Excitation PSDs').setSelected(True)
    pump()
    assert pane.spectra_actions['ratio'].isVisible(), \
        'the pair earns the reading'
    assert pane.spectra_actions['overlay'].isChecked(), \
        'overlaid stays the default'
    pane.spectra_actions['ratio'].trigger()
    pump()
    plot = next(item for item in pane.graphics.ci.items
                if isinstance(item, pg.PlotItem))
    curves = [c for c in plot.listDataItems()
              if getattr(c, 'name', lambda: None)()]
    assert len(curves) == 2, 'one curve per shared channel'
    x, y = curves[0].getData()
    assert np.nanmax(x) == pytest.approx(1000.0), \
        'linear frequency, not a logged axis'
    assert np.allclose(y[np.isfinite(y)], 30.0), \
        'a thousandfold power ratio reads 30 dB'
    # a lone PSD, or three, does not offer it
    window.tree.clearSelection()
    window._item_for_object('Noise PSDs').setSelected(True)
    pump()
    assert not pane.spectra_actions['ratio'].isVisible()


